// Generates src/integrations/supabase/types.ts (the `Database` type supabase-js uses) from supabase/migrations —
// the same shape `supabase gen types typescript` emits, without Docker: builds a throwaway database on the local
// test cluster (stubs + migrations), reads the catalog, drops it. Run after changing a migration:
//   bash tests/e2e/setup.sh   (once per container: the Postgres cluster on :54329)
//   npm run db:types
import { execFileSync } from "node:child_process";
import { readdirSync, writeFileSync } from "node:fs";

const ROOT = new URL("..", import.meta.url).pathname;
const OUT = `${ROOT}src/integrations/supabase/types.ts`;
const DB = "mapapp_types";
const env = { ...process.env, PGHOST: process.env.PGHOST ?? "/tmp", PGPORT: process.env.PGPORT ?? "54329", PGUSER: process.env.PGUSER ?? "postgres" };
const psql = (...args) => execFileSync("psql", ["-q", "-v", "ON_ERROR_STOP=1", ...args], { env, stdio: ["ignore", "pipe", "pipe"] }).toString();
psql("-c", `drop database if exists ${DB}`, "-c", `create database ${DB}`);
try {
  execFileSync("psql", ["-q", "-d", DB, "-f", `${ROOT}supabase/tests/supabase_stubs.sql`], { env, stdio: "ignore" }); // roles may exist already
} catch {
  /* errors for existing roles are expected */
}
for (const m of readdirSync(`${ROOT}supabase/migrations`).filter((f) => f.endsWith(".sql")).sort()) {
  psql("-d", DB, "-1", "-f", `${ROOT}supabase/migrations/${m}`);
}
const q = (sql) => JSON.parse(psql("-d", DB, "-At", "-c", `select coalesce(json_agg(x), '[]') from (${sql}) x`));

const SCALARS = {
  uuid: "string", text: "string", varchar: "string", bpchar: "string", citext: "string", bytea: "string",
  int2: "number", int4: "number", int8: "number", float4: "number", float8: "number", numeric: "number",
  bool: "boolean", timestamptz: "string", timestamp: "string", date: "string", time: "string", interval: "string",
  json: "Json", jsonb: "Json", void: "undefined", record: "Json",
};
const ts = (t) => (t.startsWith("_") ? `${ts(t.slice(1))}[]` : (SCALARS[t] ?? "unknown"));

const columns = q(`
  select c.relname as table, a.attname as name, t.typname as type, not a.attnotnull as nullable,
         (a.atthasdef or a.attidentity <> '') as has_default
  from pg_class c join pg_attribute a on a.attrelid = c.oid join pg_type t on t.oid = a.atttypid
  where c.relnamespace = 'public'::regnamespace and c.relkind in ('r', 'p') and a.attnum > 0 and not a.attisdropped
  order by c.relname, a.attnum`);
const fks = q(`
  select c.conname as name, cl.relname as table, rf.relname as ref,
         (select array_agg(a.attname order by k.n) from unnest(c.conkey) with ordinality k(attnum, n)
            join pg_attribute a on a.attrelid = c.conrelid and a.attnum = k.attnum) as cols,
         (select array_agg(a.attname order by k.n) from unnest(c.confkey) with ordinality k(attnum, n)
            join pg_attribute a on a.attrelid = c.confrelid and a.attnum = k.attnum) as ref_cols,
         exists (select 1 from pg_index i where i.indrelid = c.conrelid and i.indisunique
                 and (i.indkey::int2[])::int[] @> c.conkey::int[] and (i.indkey::int2[])::int[] <@ c.conkey::int[]) as one_to_one
  from pg_constraint c join pg_class cl on cl.oid = c.conrelid join pg_class rf on rf.oid = c.confrelid
  where c.contype = 'f' and cl.relnamespace = 'public'::regnamespace and rf.relnamespace = 'public'::regnamespace
  order by c.conname`);
const fns = q(`
  select p.proname as name, p.proretset as setof, rt.typname as ret,
         coalesce(p.proargnames, '{}') as argnames,
         coalesce((select array_agg(t.typname order by n) from unnest(coalesce(p.proallargtypes, p.proargtypes::oid[])) with ordinality u(oid, n)
                   join pg_type t on t.oid = u.oid), '{}') as argtypes,
         coalesce(p.proargmodes::text[], '{}') as argmodes, p.pronargs as nin, p.pronargdefaults as ndefaults
  from pg_proc p join pg_type rt on rt.oid = p.prorettype
  where p.pronamespace = 'public'::regnamespace and p.prokind = 'f' and rt.typname <> 'trigger'
  order by p.proname`);

const tables = {};
for (const c of columns) (tables[c.table] ??= []).push(c);
const ind = (n) => " ".repeat(n);
let out = `// Generated by scripts/gen-db-types.mjs from supabase/migrations — do not edit by hand.
export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];

export type Database = {
  __InternalSupabase: { PostgrestVersion: "12" };
  public: {
    Tables: {
`;
for (const [name, cols] of Object.entries(tables)) {
  const field = (c, mode) => {
    const opt = mode === "Update" || (mode === "Insert" && (c.nullable || c.has_default)) ? "?" : "";
    return `${ind(10)}${c.name}${opt}: ${ts(c.type)}${c.nullable ? " | null" : ""};\n`;
  };
  out += `${ind(6)}${name}: {\n`;
  for (const mode of ["Row", "Insert", "Update"]) {
    out += `${ind(8)}${mode}: {\n${cols.map((c) => field(c, mode)).join("")}${ind(8)}};\n`;
  }
  out += `${ind(8)}Relationships: [\n`;
  for (const f of fks.filter((f) => f.table === name)) {
    out += `${ind(10)}{ foreignKeyName: "${f.name}"; columns: ${JSON.stringify(f.cols)}; isOneToOne: ${f.one_to_one}; referencedRelation: "${f.ref}"; referencedColumns: ${JSON.stringify(f.ref_cols)} },\n`;
  }
  out += `${ind(8)}];\n${ind(6)}};\n`;
}
out += `${ind(4)}};\n${ind(4)}Views: { [_ in never]: never };\n${ind(4)}Functions: {\n`;
for (const f of fns) {
  const ins = [], outs = [];
  f.argtypes.forEach((t, i) => {
    const mode = f.argmodes[i] ?? "i";
    const name = f.argnames[i] ?? `arg${i}`;
    if (mode === "i" || mode === "b") ins.push({ name, t });
    if (mode === "o" || mode === "b" || mode === "t") outs.push({ name, t });
  });
  const firstDefault = f.nin - f.ndefaults;
  const args = ins.length
    ? `{ ${ins.map((a, i) => `${a.name}${i >= firstDefault ? "?" : ""}: ${ts(a.t)}`).join("; ")} }`
    : "Record<PropertyKey, never>";
  let ret;
  if (outs.length) ret = `{ ${outs.map((o) => `${o.name}: ${ts(o.t)}`).join("; ")} }${f.setof ? "[]" : ""}`;
  else ret = `${ts(f.ret)}${f.setof ? "[]" : ""}`;
  out += `${ind(6)}${f.name}: { Args: ${args}; Returns: ${ret} };\n`;
}
out += `${ind(4)}};\n${ind(4)}Enums: { [_ in never]: never };\n${ind(4)}CompositeTypes: { [_ in never]: never };\n  };\n};\n`;
writeFileSync(OUT, out);
psql("-c", `drop database ${DB}`);
console.log(`wrote ${OUT}: ${Object.keys(tables).length} tables, ${fns.length} functions`);
